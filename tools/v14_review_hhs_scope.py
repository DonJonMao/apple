"""Verify the existing HHS source and optionally add its bounded 1.4.5 explanation.

The original PDF and source library stay local. Existing releases and independent
evaluation artifacts are hash-checked, never regenerated by this tool.
"""

from __future__ import annotations

import argparse
import io
import json
from pathlib import Path

from healthzip.knowledge import KnowledgeWorkbench
from healthzip.knowledge.store import digest, now

ROOT = Path(__file__).resolve().parents[1]
OUTPUT_NAMES = {"HHS_goal_scope_review.json", "hhs_goal_scope-1.4.5.json", "release-1.4.5.json"}


def explanation_contract():
    definition = json.loads((ROOT / "src/healthzip/knowledge/data/hhs_goal_scope.json").read_text())
    version = definition["source_version_id"]
    parts = [{"part_id": p["part_id"], "text": p["text"],
              "span_ids": [version + f":s{i:05d}" for i in p["span_indices"]],
              "evidence_relation": p["evidence_relation"]}
             for p in definition["answer_parts"]]
    claim = {"claim_id": definition["claim_id"], "version": definition["version"],
             "statement": "\n".join(p["text"] for p in parts), "scope": definition["scope"],
             "limitations": definition["limitations"], "numeric": False,
             "evidence_links": [{"source_id": definition["source_id"], "source_version_id": version,
                                 "span_ids": sorted({s for p in parts for s in p["span_ids"]})}],
             "answer_task": {**{k: definition[k] for k in ("subject", "outcome", "requested_relation")},
                             "evidence_relation": "supports", "answer_complete": True,
                             "required_answer_parts": [p["part_id"] for p in parts],
                             "routes": definition["routes"], "answer_parts": parts}}
    rule = {"rule_id": definition["rule_id"], "rule_version": definition["version"],
            "requested_capability": "source_explanation",
            "capability_policy_version": "personal-trial-policy-1.4.0",
            "claim_refs": [{"claim_id": claim["claim_id"], "version": claim["version"]}],
            "routes": definition["routes"], "permitted_actions": [], "numeric_provenance": [],
            "conditions": [{"field": "requested_capability", "op": "eq",
                            "value": "source_explanation", "origin": "product_scope"}],
            "coverage_scope": "hhs_chapter_4_adult_public_health_goal_scope_only",
            "application_logic": "解释HHS第4章18–64岁成人健康范围、每周至少两天的肌力活动建议，以及其不能单独确定个人唯一最优力量或增肌安排的边界。按精确来源回答，不混入S1观点，不输出个人训练参数或候选。",
            "limits": definition["limitations"],
            "remaining_source_gaps": definition["remaining_personal_inference_gaps"],
            "forbidden": ["numeric_training_candidate", "unique_individual_optimum",
                          "individual_prediction", "causal_effect"],
            "implementation_validation_refs": [
                "tests/unit/test_hhs_goal_scope_contract.py",
                "src/healthzip/knowledge/core.py::core_principles"]}
    return definition, claim, rule


def verify_source(w, definition):
    """Re-extract all eleven Chapter 4 pages and verify exact reviewed spans."""
    import pdfplumber

    version = w.lib.sources.execute("SELECT * FROM version WHERE version_id=?",
                                   (definition["source_version_id"],)).fetchone()
    if not version or version["source_id"] != definition["source_id"] or version["identity_status"] != "matched":
        raise ValueError("reviewed HHS source version missing or identity unmatched")
    raw = (w.root / version["storage_uri"]).read_bytes()
    if digest(raw) != definition["raw_sha256"] or version["sha256"] != definition["raw_sha256"]:
        raise ValueError("reviewed HHS PDF bytes changed")
    rights = json.loads(version["rights_json"])
    policy = w.root / "core_acquisition/hhs_rights.raw"
    if (not rights.get("index_allowed") or rights.get("license_id") != "US-HHS-public-domain-text"
            or rights.get("rights_evidence_sha256") != definition["rights_evidence_sha256"]
            or digest(policy.read_bytes()) != definition["rights_evidence_sha256"]):
        raise ValueError("reviewed HHS federal prose rights changed")
    spans = []
    with pdfplumber.open(io.BytesIO(raw)) as pdf:
        if len(pdf.pages) != 118:
            raise ValueError("unexpected HHS PDF page count")
        for i in range(11):
            span = w.lib.span(definition["source_version_id"] + f":s{i:05d}")
            page = pdf.pages[54 + i]
            text = page.extract_text() or ""
            locator = json.loads(span["locator_json"]) if span else {}
            if (not span or span["text"] != text or span["text_hash"] != digest(text.encode())
                    or locator.get("chapter_id") != "4" or locator.get("file_page_index") != 54 + i
                    or locator.get("printed_page_label") != str(55 + i)
                    or locator.get("bounding_box") != list(page.bbox)):
                raise ValueError("stored HHS Chapter 4 text or locator differs from PDF")
            spans.append(span)
    locators = []
    for expected in definition["reviewed_spans"]:
        span = spans[expected["span_index"]]
        if span["text_hash"] != expected["text_hash"] or not w.lib.eligible(span, "fulltext")[0]:
            raise ValueError("reviewed HHS evidence changed or is no longer eligible")
        locators.append({"span_id": span["span_id"], "text_hash": span["text_hash"],
                         "locator": json.loads(span["locator_json"])})
    return spans, rights, locators


def snapshot(w):
    return {name: [dict(r) for r in w.lib.theories.execute(f"SELECT * FROM {name} ORDER BY 1,2")]
            for name in ("source_claim", "application_rule", "core_release")}


def frozen_hashes():
    # Development verification artifacts may be added by concurrent workers;
    # only prior releases and frozen evaluations are invariants of this change.
    names = ("release.json", "core_claims.jsonl", "advice_rules.jsonl", "release-1.4.4.json",
             "method_explanation-1.4.4.json", "M2_method_review.json", "N2_repository_review.json",
             "method_source_round3.json", "method-release-verification.json", "method-verification.xml")
    paths = {ROOT / "artifacts/v14/knowledge" / name for name in names}
    for pattern in ("artifacts/v14/knowledge/independent*", "artifacts/v14/knowledge/rag_*.json",
                    ".local/v14-knowledge-independent*/*",
                    ".local/v14-knowledge-evaluation/independent*"):
        paths.update(p for p in ROOT.glob(pattern) if p.is_file())
    paths.update(ROOT / "src/healthzip/knowledge/data" / name
                 for name in ("rag_eval_cases.json", "rag_holdout.json"))
    return {str(p.relative_to(ROOT)): digest(p.read_bytes()) for p in sorted(paths)}


def reviewed_record(w, table, field, identifier, version, *, application=False):
    row = w.lib.theories.execute(
        f"SELECT review_json FROM {table} WHERE {field}=? AND version=?", (identifier, version)
    ).fetchone()
    if row:
        return json.loads(row[0])
    return {"reviewer": "Codex HHS source and application review", "reviewer_kind": "ai_assisted",
            "reviewed_at": now(), "independent_expert_validation": False,
            "application_checked" if application else "content_checked": True,
            "rationale": (
                "Reread actual Chapter 4 printed pages 55-65. Pages 56/57 establish adult age and health scope; "
                "pages 56/61/63 establish the general minimum muscle-strengthening recommendation; "
                "pages 61-63 describe progression and personal health/fitness goals. The non-unique-optimum "
                "conclusion is a bounded interpretation of that scope, not an HHS hypertrophy trial result. "
                "No claim that two days cannot produce strength or hypertrophy, no S1 evidence, "
                "and no personal calibration or candidate authority."
            )}


def existing_or_create_release(w, release_id):
    row = w.lib.theories.execute(
        "SELECT manifest_json,sha256 FROM core_release WHERE release_id=?", (release_id,)
    ).fetchone()
    if row:
        if digest(row["manifest_json"].encode()) != row["sha256"]:
            raise ValueError("stored immutable release hash mismatch")
        return {"release_id": release_id, "sha256": row["sha256"], **json.loads(row["manifest_json"])}
    return w.release_core(release_id)


def write_public(path, value, spans):
    encoded = json.dumps(value, ensure_ascii=False, indent=2) + "\n"
    # A JSON release embeds serialized JSON strings; decode recursively to catch
    # source prose there as well as in direct string fields.
    def strings(item):
        if isinstance(item, str):
            yield item
            if item.lstrip().startswith(("{", "[")):
                try:
                    yield from strings(json.loads(item))
                except json.JSONDecodeError:
                    pass
        elif isinstance(item, dict):
            for child in item.values():
                yield from strings(child)
        elif isinstance(item, list):
            for child in item:
                yield from strings(child)

    public = " ".join(" ".join(s.split()) for s in strings(value))
    for span in spans:
        prose = " ".join(span["text"].split())
        if len(prose) >= 120 and prose[:120] in public:
            raise ValueError("public output contains source body text")
    if path.exists():
        if json.loads(path.read_text()) != value:
            raise ValueError("public explanation artifact immutable; use a new version")
        # Initial release construction and frozen JSON reads can use different
        # dictionary insertion order. Keep the original public bytes unchanged.
        return
    path.write_text(encoded)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--knowledge-root", type=Path, default=ROOT / ".local/knowledge")
    parser.add_argument("--output-dir", type=Path, default=ROOT / "artifacts/v14/knowledge")
    parser.add_argument("--activate-explanation", action="store_true")
    args = parser.parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    definition, claim, rule = explanation_contract()
    frozen_before = frozen_hashes()
    w = KnowledgeWorkbench(args.knowledge_root)
    try:
        before = snapshot(w)
        spans, rights, locators = verify_source(w, definition)
        if snapshot(w) != before:
            raise ValueError("source verification changed knowledge contracts")
        report = {"source_id": definition["source_id"], "source_version_id": definition["source_version_id"] ,
                  "raw_sha256": definition["raw_sha256"], "rights": rights,
                  "read_printed_pages": list(range(55, 66)), "reviewed_locators": locators,
                  "reviewer_kind": "ai_assisted", "independent_human_or_expert_reviews": 0,
                  "review_summary": [p["text"] for p in definition["answer_parts"]],
                  "interpretation_boundary": "The optimization limit is a scope interpretation, not a tested hypertrophy outcome.",
                  "source_verification_mutations": 0, "personal_calibration_supplied": False}
        output = {"HHS_goal_scope_review.json": report}
        if args.activate_explanation:
            previous = w.lib.theories.execute("SELECT manifest_json,sha256 FROM core_release WHERE release_id=?",
                                              (definition["previous_release_id"],)).fetchone()
            if not previous or digest(previous["manifest_json"].encode()) != previous["sha256"]:
                raise ValueError("expected immutable 1.4.4 base release missing or corrupt")
            content_review = reviewed_record(w, "source_claim", "claim_id", claim["claim_id"], claim["version"])
            application_review = reviewed_record(w, "application_rule", "rule_id", rule["rule_id"], rule["rule_version"], application=True)
            w.review_claim(claim, content_review)
            w.review_rule(rule, application_review)
            release = existing_or_create_release(w, definition["release_id"])
            base = json.loads(previous["manifest_json"])
            for key in ("claims", "rules"):
                if len(release[key]) != len(base[key]) + 1 or any(row not in release[key] for row in base[key]):
                    raise ValueError("1.4.5 must add exactly one HHS claim and rule to 1.4.4")
            for route in definition["routes"]:
                if any(p["rule_id"] == rule["rule_id"] for p in w.reviewed_principles(route, {"requested_capability": "source_explanation"})["principles"]):
                    raise ValueError("HHS explanation acquired candidate authority")
            output["release-1.4.5.json"] = release
            output["hhs_goal_scope-1.4.5.json"] = {
                "claim": claim, "content_review": content_review, "rule": rule,
                "application_review": application_review, "source_corpus_roles": ["core"],
                "release_id": release["release_id"], "release_sha256": release["sha256"],
                "previous_release_id": definition["previous_release_id"], "previous_release_sha256": previous["sha256"],
                "claims_in_release": len(release["claims"]), "rules_in_release": len(release["rules"]),
                "personal_calibration_supplied": False, "independent_human_or_expert_reviews": 0,
                "previous_release_records_unchanged": True}
        after = snapshot(w)
        if any(row not in after[table] for table, rows in before.items() for row in rows):
            raise ValueError("pre-existing immutable knowledge record changed")
        if frozen_hashes() != frozen_before:
            raise ValueError("pre-existing public artifact or independent evaluation changed")
        for name, value in output.items():
            write_public(args.output_dir / name, value, spans)
        print(json.dumps({"source_verified": True, "explanation_activated": args.activate_explanation,
                          "release_id": definition["release_id"] if args.activate_explanation else None,
                          "previous_records_and_evaluations_unchanged": True}, ensure_ascii=False))
    finally:
        w.close()


if __name__ == "__main__":
    main()
