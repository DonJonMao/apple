PATTERNS = [
    (re.compile(r"(?<![a-z])" + re.escape(source) + r"(?![a-z])"), target)
    for source, target in sorted(TERMS.items(), key=lambda kv: -len(kv[0]))
]


def translate_name(name):
    remaining = name.lower().strip()
    placeholders = {}
    for index, (pattern, target) in enumerate(PATTERNS):
        # A single private-use character cannot be rewritten by later numeric terms.
        token = chr(0xE000 + index)
        updated, count = pattern.subn(token, remaining)
        if count:
            placeholders[token] = target
            remaining = updated
    unresolved = sorted(set(re.findall(r"[a-z]{2,}", remaining)))
    for key, value in placeholders.items():
        remaining = remaining.replace(key, value)
    return remaining.strip(), unresolved
